#!/usr/bin/env node
// Generates CONTROLLER_GRAMMAR_CODES.md from the
// CONTROLLER_GRAMMAR_FIXES catalogue plus the live `CG_*` codes that
// `controllerGrammar.ts` emits today through the public `lint()` API.
//
// For every catalogue entry we render a row containing code + canonical
// title + rationale, plus a fenced replacement-template block. We also
// drift-check: every code emitted by the live linter on the trigger
// fixtures MUST resolve through `getControllerGrammarFix` — unknown
// codes abort with exit code 1.
//
// Wired into the root `verify` chain via `npm run docs:cg-codes`. Requires
// `@cnc/core` and the profile packs to be built first (so the workspace
// symlink resolves to `dist/` entries).

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  CG_DUPLICATE_ADDRESSES_PREFIX,
  CONTROLLER_GRAMMAR_FIXES,
  getControllerGrammarFix,
  lint,
  parse
} from "@cnc/core";
import { fanucIsoProfile } from "@cnc/profile-fanuc-iso";
import { haasNgcProfile } from "@cnc/profile-haas-ngc";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const FANUC_TRIGGERS = [
  "G0 X0",
  "O1234 N5",
  "O999999999",
  "G65 P9000 K1 J2 I3",
  "O1234",
  "O1234",
  "G1 X1 X2 Y3 Y4 F100"
].join("\n");

const HAAS_TRIGGERS = [
  "O1234 N5",
  "G65 P9000 K1 J2 I3",
  "G1 X1 X2 Y3 Y4 F100"
].join("\n");

function collectEmittedCodes(source, profile) {
  const ast = parse(source, profile);
  const codes = new Set();
  for (const issue of lint(ast, profile)) {
    if (issue.code) codes.add(issue.code);
  }
  return codes;
}

function escapeCell(value) {
  return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function renderTemplate(template) {
  if (!template) return "_(no template)_";
  return ["```", template, "```"].join("\n");
}

function renderEntry(entry) {
  const lines = [];
  lines.push(`### \`${entry.code}\``);
  lines.push("");
  lines.push(`- **Canonical fix:** ${entry.title}`);
  lines.push(`- **Rationale:** ${entry.rationale}`);
  lines.push("");
  lines.push("**Replacement template:**");
  lines.push("");
  lines.push(renderTemplate(entry.replacementTemplate));
  lines.push("");
  return lines.join("\n");
}

async function main() {
  const fanucCodes = collectEmittedCodes(FANUC_TRIGGERS, fanucIsoProfile);
  const haasCodes = collectEmittedCodes(HAAS_TRIGGERS, haasNgcProfile);
  const emittedCgCodes = new Set(
    [...fanucCodes, ...haasCodes].filter((c) => c.startsWith("CG_"))
  );

  const drift = [];
  for (const code of emittedCgCodes) {
    if (!getControllerGrammarFix(code)) drift.push(code);
  }
  if (drift.length > 0) {
    throw new Error(
      `controllerGrammar emitted codes with no catalogue entry: ${drift.sort().join(", ")}\n` +
        `Add an entry to packages/core/src/lints/controllerGrammarFixes.ts and re-run.`
    );
  }

  const catalogueKeys = Object.keys(CONTROLLER_GRAMMAR_FIXES).sort((a, b) =>
    a.localeCompare(b)
  );

  const header = [
    "<!-- AUTO-GENERATED by scripts/generate-controller-grammar-codes.mjs — DO NOT EDIT BY HAND. -->",
    "<!-- Re-run `npm run docs:cg-codes` after editing controllerGrammarFixes.ts or controllerGrammar.ts. -->",
    "",
    "# CNC Workbench — Controller-grammar rule codes reference",
    "",
    "Every controller-grammar lint (`packages/core/src/lints/controllerGrammar.ts`) attaches a stable `code` to each issue.",
    `These codes are mapped to canonical fixes in \`packages/core/src/lints/controllerGrammarFixes.ts\` (\`${CG_DUPLICATE_ADDRESSES_PREFIX}*\` is a per-letter family).`,
    "Downstream tools (IDE quick-fixes, batch auto-fixers, CLI envelope cross-tables) look up fixes by code rather than scraping rule messages.",
    "",
    `Total catalogue entries: ${catalogueKeys.length}`,
    `Live emitted codes verified at generation time: ${emittedCgCodes.size} (${[...emittedCgCodes]
      .sort()
      .join(", ")})`,
    "",
    "| Code | Canonical fix | Rationale |",
    "| --- | --- | --- |"
  ];

  const tableRows = catalogueKeys.map((key) => {
    const entry = CONTROLLER_GRAMMAR_FIXES[key];
    return `| \`${escapeCell(entry.code)}\` | ${escapeCell(entry.title)} | ${escapeCell(entry.rationale)} |`;
  });

  const detailSections = catalogueKeys.map((key) => renderEntry(CONTROLLER_GRAMMAR_FIXES[key]));

  const output =
    header.concat(tableRows).concat([""]).concat(detailSections).join("\n").trimEnd() + "\n";

  const outPath = path.join(repoRoot, "CONTROLLER_GRAMMAR_CODES.md");
  await writeFile(outPath, output, "utf8");
  process.stdout.write(
    `Wrote ${outPath} (${catalogueKeys.length} catalogue entries; ${emittedCgCodes.size} emitted codes verified)\n`
  );
}

main().catch((err) => {
  process.stderr.write(
    `generate-controller-grammar-codes failed: ${err && err.stack ? err.stack : err}\n`
  );
  process.exit(1);
});
